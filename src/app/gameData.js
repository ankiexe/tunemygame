const resMultipliers = { "720p": 1.6, "1080p": 1.0, "1440p": 0.72, "4K": 0.45 };

export function getTunedProfile(game, cpu, gpu, ramCap, ramType, resolution, mode = "competitive") {
  let cpuData = cpuScores[cpu];
  if (!cpuData) {
    let score = 50;
    let tdp = 65;
    if (/i9|ryzen 9|9800x3d|7800x3d|285k/i.test(cpu)) { score = 98; tdp = 180; }
    else if (/i7|ryzen 7|14700|13700|7700/i.test(cpu)) { score = 88; tdp = 125; }
    else if (/i5|ryzen 5|14600|13600|7600|5600/i.test(cpu)) { score = 70; tdp = 95; }
    else if (/i3|ryzen 3|12100|3200g/i.test(cpu)) { score = 40; tdp = 60; }
    else if (/quad|duo|fx|athlon|phenom/i.test(cpu)) { score = 15; tdp = 95; }
    cpuData = { score, tdp };
  }

  let gpuData = gpuScores[gpu];
  if (!gpuData) {
    let score = 30;
    let vram = 6;
    let tdp = 120;
    if (/5090|4090|7900 xtx/i.test(gpu)) { score = 180; vram = 24; tdp = 450; }
    else if (/4080|5080|7900 xt/i.test(gpu)) { score = 120; vram = 16; tdp = 320; }
    else if (/4070|3080|7800 xt/i.test(gpu)) { score = 88; vram = 12; tdp = 220; }
    else if (/4060|3060|6700 xt|7600/i.test(gpu)) { score = 55; vram = 8; tdp = 140; }
    else if (/1660|1650|1060|580|570/i.test(gpu)) { score = 24; vram = 6; tdp = 90; }
    else if (/750|1030|710|hd|uhd|vega|iris|igpu/i.test(gpu)) { score = 6; vram = 2; tdp = 25; }
    gpuData = { score, vram, tdp };
  }

  const isIGPU = gpu.startsWith("[iGPU]") || gpuData.score <= 12;

  let gameInfo = specificGameWeights[game];
  if (!gameInfo) {
    const isRPG = /witcher|scrolls|fallout|fantasy|persona|yakuza|dragon|souls|elden|tales|octopath|divinity|gate|disco/i.test(game);
    const isRacing = /forza|assetto|wrc|rally|crew|motorsport|racing|drift|dirt|grid|f1/i.test(game);
    const isShooterOrEsport = /war|battle|siege|strike|ops|apex|overwatch|fort|squad|tarkov|finals|counter/i.test(game);
    const isHeavyNextGen = /2|remake|survivor|shadows|myth|wukong|flight|stalker|lords|veilguard|detroit/i.test(game);
    const isIndieOr2D = /hades|cells|slay|binding|stardew|vampire|celeste|inside|terrar|lethal/i.test(game);

    if (isIndieOr2D) {
      gameInfo = { baseFps: 240, cpuBias: 0.25, vramDemand: 2.0, storage: "10 GB", dx: "DirectX 11 / OpenGL", mac: "Native (macOS)", gamePass: false, gfn: true, isEsport: false };
    } else if (isRPG) {
      gameInfo = { baseFps: 75, cpuBias: 0.45, vramDemand: 6.0, storage: "65 GB", dx: "DirectX 11 / DX12", mac: "No (CrossOver)", gamePass: false, gfn: true, isEsport: false };
    } else if (isRacing) {
      gameInfo = { baseFps: 90, cpuBias: 0.35, vramDemand: 6.0, storage: "75 GB", dx: "DirectX 12", mac: "No (Windows Only)", gamePass: false, gfn: true, isEsport: false };
    } else if (isShooterOrEsport) {
      gameInfo = { baseFps: 110, cpuBias: 0.55, vramDemand: 4.5, storage: "65 GB", dx: "DirectX 11 / DX12", mac: "No (Anti-Cheat)", gamePass: false, gfn: true, isEsport: true };
    } else if (isHeavyNextGen) {
      gameInfo = { baseFps: 55, cpuBias: 0.35, vramDemand: 7.5, storage: "85 GB (SSD Req)", dx: "DirectX 12 Ultimate", mac: "No (Windows Only)", gamePass: true, gfn: true, isEsport: false };
    } else {
      gameInfo = { baseFps: 85, cpuBias: 0.4, vramDemand: 4.8, storage: "45 GB", dx: "DirectX 11 / DX12", mac: "No (CrossOver GPTK)", gamePass: false, gfn: true, isEsport: false };
    }
  }

  const resMul = resMultipliers[resolution] || 1.0;
  const isCinematic = mode === "cinematic";

  let ramPenalty = 1.0;
  if (ramCap === "4 GB") ramPenalty *= 0.52;
  else if (ramCap === "8 GB") ramPenalty *= isIGPU ? 0.70 : 0.76;
  if (ramType.includes("DDR3")) ramPenalty *= 0.80;
  if (ramType.includes("6000+ MHz")) ramPenalty *= 1.06;

  const cpuFactor = cpuData.score / 60;
  const gpuFactor = (gpuData.score / 45) * resMul * (isCinematic ? 0.78 : 1.05);

  const effectivePower = (gpuFactor * (1 - gameInfo.cpuBias) + cpuFactor * gameInfo.cpuBias) * ramPenalty;
  let calculatedFps = Math.round(gameInfo.baseFps * effectivePower);

  // Engine Framerate Locks
  const locked60Titles = [
    "Elden Ring",
    "Detroit: Become Human",
    "Tales of Symphonia",
    "Tales of Berseria",
    "Tales of Zestiria",
    "Final Fantasy X/X-2 HD Remaster",
    "Final Fantasy XIII",
    "Dark Souls: Remastered",
    "Dark Souls II: Scholar of the First Sin",
    "Dark Souls III",
    "NieR: Automata",
    "Mortal Kombat 1",
    "Street Fighter 6",
    "Tekken 8"
  ];

  if (locked60Titles.includes(game) && calculatedFps > 60) calculatedFps = 60;
  if (gameInfo.isEsport && calculatedFps > 550) calculatedFps = 550;

  const isUnplayableLocally = calculatedFps < 28;
  if (calculatedFps < 8) calculatedFps = 8;

  const totalWeight = cpuData.score + gpuData.score * (1 / resMul);
  const cpuPct = Math.round((gpuData.score * (1 / resMul) / totalWeight) * 100);
  const gpuPct = 100 - cpuPct;

  let bottleneck = {
    status: cpuPct > 62 ? `CPU Limit (${cpuPct}%)` : gpuPct > 68 ? `GPU Bound (${gpuPct}%)` : "Balanced Rig",
    color: cpuPct > 62 ? "text-amber-400" : gpuPct > 68 ? "text-sky-400" : "text-emerald-400",
    cpuUsage: cpuPct,
    gpuUsage: gpuPct,
    message: cpuPct > 62
      ? `Framerate constrained by ${cpu}. Open-world and NPC-dense zones may exhibit stutter.`
      : gpuPct > 68
      ? `${gpu} is fully saturated. Enjoy consistent frametimes or increase resolution.`
      : "Balanced CPU/GPU synergy for this RPG engine."
  };

  const resVramMultiplier = resolution === "4K" ? 1.45 : resolution === "1440p" ? 1.2 : 1.0;
  const estimatedVramUsed = Number((gameInfo.vramDemand * resVramMultiplier * (isCinematic ? 1.25 : 0.85)).toFixed(1));
  const vramSaturationPct = Math.min(100, Math.round((estimatedVramUsed / gpuData.vram) * 100));

  const estimatedTdp = cpuData.tdp + gpuData.tdp + 60;
  const recommendedPsu = Math.ceil((estimatedTdp * 1.35) / 50) * 50;

  const settings = [
    { name: "Render Scaling", value: isIGPU || gpuData.score < 10 ? "720p @ 65% FSR" : "100% Native" },
    { name: "Texture Resolution", value: vramSaturationPct > 90 ? "Medium / Low" : gpuData.vram >= 8 ? "High / Ultra" : "Medium" },
    { name: "Shadow Quality", value: isCinematic && gpuData.score > 60 ? "High / Ultra" : "Low / Disabled" },
    { name: "Volumetric Lighting & Fog", value: isCinematic && gpuData.score > 70 ? "High" : "Low / Off" },
    { name: "Crowd / NPC Density", value: cpuData.score >= 60 ? "High" : "Medium / Low" },
    { name: "Ray Tracing / Ambient Occlusion", value: isCinematic && gpuData.score >= 115 ? "Optimized / Light" : "Off (Max Frames)" },
    { name: "Reflex / Low Latency Mode", value: "On + Boost" }
  ];

  return {
    expectedFps: `${Math.round(calculatedFps * 0.92)} - ${Math.round(calculatedFps * 1.08)} FPS`,
    numericFps: calculatedFps,
    onePercentLow: `${Math.max(4, Math.round(calculatedFps * 0.70))} FPS`,
    storageRequired: gameInfo.storage,
    directX: gameInfo.dx,
    macSupport: gameInfo.mac,
    isGamePass: gameInfo.gamePass,
    isGfn: gameInfo.gfn,
    isUnplayableLocally,
    bottleneck,
    vramTelemetry: {
      used: estimatedVramUsed,
      total: gpuData.vram,
      percent: vramSaturationPct,
      isOverloaded: vramSaturationPct >= 95
    },
    powerDraw: {
      wattage: estimatedTdp,
      psu: recommendedPsu
    },
    settings
  };
}